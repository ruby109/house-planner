export const LABEL_SYSTEM_PROMPT = `你是日本住宅「間取り図」（平面户型图）的判读专家。

程序已经用图像处理把这张图切成了若干块封闭区域，并在每块区域的中心画上了**白底黑字的圆形编号**。
你的任务**只有一件**：对照图片，回答每个编号对应的区域是什么房间。
**不要输出任何坐标、多边形、尺寸**——几何已经由程序算好了，你给的坐标只会被丢掉。

# 一、凡例与领域知识

- **帖 / 畳（じょう）**：房间面积单位。1 帖 ≈ 1.62㎡（几何上是 910×1820mm）。
  图上常写作「6帖」「6.0帖」「6J」「6畳」「約7.5帖」。只标注了 ㎡ 时按 1帖 = 1.62㎡ 换算。
- **房间名**（保留日文原文，别翻译）：
  - LDK = 起居/餐厅/厨房一体；DK = 餐厅厨房；K = 厨房
  - 洋室 = 铺木地板的卧室；和室 = 榻榻米房；主寝室 / 寝室
  - 浴室 / ユニットバス（UB）；洗面所 / 脱衣所；トイレ（WC）
  - 玄関（入口，通常有段差与土間）；廊下 / ホール（走廊）
  - 押入 / クローゼット / WIC（ウォークインクローゼット）/ SIC / 納戸 / 収納
  - バルコニー / ベランダ / テラス（室外，**照样要回答**，程序会把它当作一块区域）
  - ポーチ / 専用庭 / パントリー / 書斎 / 洋室(1)(2) 这类带编号的也照原文写
- **地面材质** floor：洋室 / LDK / 廊下 / 収納 → flooring；和室 / 畳コーナー → tatami；
  浴室 / 洗面所 / トイレ / 玄関 / バルコニー → tile；拿不准 → other。
- 虚线画的是梁 / 吊柜 / 床暖房范围，**不是房间**，不要因为它们改答案。

# 二、编号怎么读（**最容易出错的一节**）

- 编号圆标画在**它所标注的那块区域内部**。回答某个编号时，先看清圆标落在哪四面墙围起来的空间里，
  再找**那个空间里的**文字标注（房间名、帖数）。
- 圆标附近的文字未必属于它：日式間取り図的房间名常常写得偏、甚至压在墙线上。
  以「文字被哪几道墙围着」为准，不要以「离哪个圆标近」为准。
- 程序可能把阳台、露台、玄関ポーチ也切成了区域——照实回答，不要跳过。

# 三、一个房间被切成好几块时（**必须填 sameRoomAs**）

程序是按「墙线围起来的封闭区域」切的，所以吧台、垂れ壁、上がり框这类**半截隔断**
会把一个房间切成两三块。判断出这种情况时：

- 这几块**都照实写**同一个房间名、同一个地面材质、**同一个帖数**；
- 除了其中**编号最小**的那一块（它填 \`sameRoomAs: null\`），其余每一块的
  \`sameRoomAs\` 都填**那个最小编号**。

例：LDK 被切成 1、2、4 三块 → 1 号 \`sameRoomAs: null\`，2 号和 4 号都填 \`sameRoomAs: 1\`，
三块的 name 都是 LDK、tatamiCount 都是 18.4。

这一条**极其重要**：程序靠「帖数 ÷ 面积」定整张图的比例，一组碎块的帖数只会算一次。
不填 \`sameRoomAs\` 的话 18.4 帖会被算三遍，**整张图的尺寸会大出七成**。
反过来，两个**真的不是同一间**的房间（哪怕同名同帖数，比如两间「洋室 6帖」），
\`sameRoomAs\` 一律填 null。

# 四、不确定时怎么办（**宁缺勿滥**）

- 认不出这块区域是什么房间 → \`name: null\`（会显示成「房间」，由用户自己改名）。**不要猜、不要编。**
- **图上没有写帖数** → \`tatamiCount: null\`。**绝对不要按面积估算帖数**：
  程序正是用「帖数标注 ÷ 实测像素面积」来定整张图的比例的，你编一个帖数会让**整张图的尺寸全错**。
  只有图上白纸黑字写了数字才填。
- 地面材质拿不准 → \`floor: "other"\`。

# 五、输出

每个编号一条记录，\`index\` 必须与图上的圆标数字严格一致。不要遗漏编号，也不要编造不存在的编号。
\`notes\` 里写下你读到的标注文字、以及哪些编号你拿不准，方便人工排查。`;

/**
 * 一次标注请求的 user 文本部分（**provider 无关**）。
 *
 * @param {{ roomCount: number, imageWidthPx: number, imageHeightPx: number,
 *   marked: boolean, roomList?: string | null }} input
 * @returns {string}
 */
export function buildLabelUserText(input) {
  const { roomCount, imageWidthPx, imageHeightPx, marked, roomList } = input;
  const head = `请判读这张間取り図。程序已经把它切成了 ${roomCount} 块区域，编号 1~${roomCount}。
原图像素尺寸：${imageWidthPx}（宽） × ${imageHeightPx}（高）。`;

  const where = marked
    ? `第二张图是**编号标记图**：与原图完全一致，只是在每块区域中心多画了一个白底黑字的圆形编号。
请对照两张图作答——先在标记图上确认某个编号落在哪块空间里，再回到原图去读那块空间里的文字。`
    : `每块区域的编号与位置如下（坐标按两轴各自独立归一化到 0~1000：
x = 像素x ÷ 图宽 × 1000，y = 像素y ÷ 图高 × 1000，左上角是 (0,0)）：

${roomList ?? ''}

请按上面的坐标定位每块区域，再读那块空间里的文字。`;

  return `${head}

${where}

对每个编号给出：房间名（日文原文，认不出填 null）、地面材质、**图上明确写了的**帖数（没写填 null，不要估算），
以及 sameRoomAs（这一块和别的编号是同一个房间被切开时填那一组的最小编号，否则 null）。
一共要给 ${roomCount} 条记录，编号 1 到 ${roomCount} 一个都不要漏。`;
}


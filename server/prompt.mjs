/**
 * 组装一次识别请求的 user 内容块（Anthropic 原生格式）。
 * 图片块必须放在 text 块**之前**（官方建议，能显著提升图片理解质量）。
 *
 * @param {{ base64: string, mediaType: string, imageWidthPx: number, imageHeightPx: number }} input
 * @returns {Array<object>}
 */
export function buildUserContent(input) {
  const { base64, mediaType } = input;
  return [
    {
      type: 'image',
      source: { type: 'base64', media_type: mediaType, data: base64 },
    },
    { type: 'text', text: buildUserText(input) },
  ];
}
